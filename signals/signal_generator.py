# Confluence result
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class ConfluenceResult:
    """
    Summary of multi-strategy confluence analysis for one trade direction.

    Attributes
    ----------
    direction          : Candidate direction ("BUY" or "SELL")
    total_active       : Number of strategies that produced an active verdict
    agreeing           : Count of active strategies agreeing with direction
    conflicting        : Count of active strategies opposing direction
    conflict_detected  : True if any active strategy voted opposite direction
    confluence_boost   : Confidence delta to apply (0.0 / +0.08 / +0.15)
    verdicts           : All StrategyVerdicts (for transparency / logging)
    """
    direction:         str
    total_active:      int   = 0
    agreeing:          int   = 0
    conflicting:       int   = 0
    conflict_detected: bool  = False
    confluence_boost:  float = 0.0
    verdicts:          list[StrategyVerdict] = field(default_factory=list)

    def summary_str(self) -> str:
        agree_names    = [v.strategy_name for v in self.verdicts if v.active and v.direction == self.direction]
        conflict_names = [v.strategy_name for v in self.verdicts if v.active and v.direction != self.direction and v.direction != "NEUTRAL"]
        parts = []
        if agree_names:
            parts.append(f"agree=[{', '.join(agree_names)}]")
        if conflict_names:
            parts.append(f"CONFLICT=[{', '.join(conflict_names)}]")
        boost_str = f"boost={self.confluence_boost:+.0%}" if self.confluence_boost else "boost=none"
        return f"{self.direction} {boost_str} active={self.total_active} {' '.join(parts)}"


