class SignalGenerator:
    """
    Multi-strategy orchestrator for the AntiGravity Gold Bot.

    Runs three independent strategy engines, combines their verdicts via a
    confluence vote, then validates each passing idea through a strict
    multi-gate filter chain.

    Three strategies
    ────────────────
    A. Trend Strategy     — EMA 50/200 crossover + slope + price position
    B. SMC Strategy       — Order blocks, FVGs, BOS, CHoCH, liquidity pools
    C. Liquidity Sweep    — Stop-hunt detection (sweep + reverse pattern)

    Confluence rules
    ────────────────
    • All 3 agree   → +0.15 boost
    • Any 2 agree   → +0.08 boost
    • Only SMC      →  no bonus
    • Any conflict  → REJECT (active strategies cannot disagree on direction)

    The SMC strategy is the primary signal source — it generates the
    candidate TradeIdeas.  Trend and LiqSweep are corroborators that boost
    or block each idea.

    Usage
    ─────
        sg = SignalGenerator(settings)
        signals, rejects = sg.generate(df_h1, df_m15, account_balance=10_000)
    """

    def __init__(
        self,
        settings:           Settings,
        news_filter:        Optional[NewsFilter]        = None,
        session_filter:     Optional[SessionFilter]     = None,
        volatility_filter:  Optional[VolatilityFilter]  = None,
        use_liquidity_map:  bool                        = True,
    ) -> None:
        """
        Parameters
        ----------
        settings            : App configuration (risk, session, ATR, R:R thresholds)
        news_filter         : If None, safe_mode=True is used (no live API)
        session_filter      : If None, constructed from settings
        volatility_filter   : If None, constructed from settings
        use_liquidity_map   : Whether to use LiquidityMapper for TP/entry guard
                              (requires strategy.liquidity_map module)
        """
        self.cfg = settings

        # ── Strategy sub-engines ──────────────────────────────────────────────
        self.trend_detector  = TrendDetector(
            slow_period  = settings.EMA_SLOW_PERIOD,
            macro_period = settings.EMA_MACRO_PERIOD,
        )
        self.regime_clf   = MarketRegimeClassifier(settings)
        self.smc          = SmartMoneyStrategy(settings)
        self.liq_detector = LiquiditySweepDetector(settings)
        self.sizer        = PositionSizer(settings)

        # Optional liquidity map
        self._use_liq_map = use_liquidity_map and _LIQUIDITY_MAP_AVAILABLE
        self.liq_mapper   = LiquidityMapper(settings) if self._use_liq_map else None

        # ── Filters ──────────────────────────────────────────────────────────
        self.session_f    = session_filter    or SessionFilter(settings)
        self.volatility_f = volatility_filter or VolatilityFilter(settings)
        self.news_f       = news_filter       or NewsFilter(settings, safe_mode=True)

        # ── Daily signal tracking ─────────────────────────────────────────────
        self._signals_today:     list[TradingSignal] = []
        self._last_reset_date:   Optional[datetime]  = None

    # =========================================================================
    # PRIMARY PUBLIC API
    # =========================================================================

    def generate(
        self,
        df_h1:           pd.DataFrame,
        df_m15:          pd.DataFrame,
        account_balance: float,
        df_m5:           Optional[pd.DataFrame] = None,
        now:             Optional[datetime]      = None,
    ) -> tuple[list[TradingSignal], list[RejectedIdea]]:
        """
        Run the full multi-strategy signal generation pipeline.

        Parameters
        ----------
        df_h1           : H1 OHLCV — trend + regime context
        df_m15          : M15 OHLCV — SMC scan + liq sweep
        account_balance : Live equity for lot sizing (USD)
        df_m5           : Optional fine-grained data (reserved for future use)
        now             : Override current UTC datetime (for testing)

        Returns
        -------
        (signals: list[TradingSignal], rejected: list[RejectedIdea])
        """
        now = now or datetime.now(timezone.utc)
        self._reset_daily_counter(now)

        signals:  list[TradingSignal] = []
        rejected: list[RejectedIdea]  = []

        # ── Step 1: Pre-scan gate ─────────────────────────────────────────────
        _dbg_log.cycle_start(now)

        sess_ok,  sess_reason = self.session_f.is_allowed(now)
        vol_ok,   vol_reason  = self.volatility_f.is_allowed(df_m15)
        news_ok,  news_reason = self.news_f.is_allowed(now)

        _dbg_log.pre_scan_filters(
            sess_ok, sess_reason,
            vol_ok,  vol_reason,
            news_ok, news_reason,
        )

        if not sess_ok:
            logger.info(f"SignalGenerator: pre-scan BLOCKED — session: {sess_reason}")
        if not vol_ok:
            logger.info(f"SignalGenerator: pre-scan BLOCKED — volatility: {vol_reason}")
        if not news_ok:
            logger.info(f"SignalGenerator: pre-scan BLOCKED — news: {news_reason}")

        hard_block = (not sess_ok) and (not vol_ok)
        if hard_block:
            logger.info("SignalGenerator: hard-block active — skipping scans")
            _dbg_log.cycle_summary(signals, rejected)
            return signals, rejected

        # ── Step 2: Shared context (runs ONCE) ───────────────────────────────
        trend_result  = self._get_trend(df_h1)
        regime_result = self._get_regime(df_h1)
        liq_sweep     = self._get_liquidity_sweep(df_m15)

        _dbg_log.context(trend_result, regime_result, liq_sweep)

        logger.info(
            f"SignalGenerator: "
            f"trend={trend_result.direction.value}({trend_result.strength:.0%})  "
            f"regime={regime_result.regime.value}  "
            f"liq_sweep={'YES' if liq_sweep else 'none'}"
        )

        # ── Step 3: Get strategy verdicts ─────────────────────────────────────
        trend_verdict = self._run_trend_strategy(trend_result)
        liq_verdict   = self._run_liq_sweep_strategy(liq_sweep)

        _dbg_log.strategy_verdicts([trend_verdict, liq_verdict])

        logger.info(
            f"Strategy verdicts:\n"
            f"  {trend_verdict}\n"
            f"  {liq_verdict}"
        )

        # ── Step 4: SMC scan — produces candidate ideas ───────────────────────
        raw_ideas = self._scan_smc(df_m15)

        if not raw_ideas:
            logger.info("SignalGenerator: SMC scan — no raw ideas")
            _dbg_log.smc_ideas([])
            _dbg_log.cycle_summary(signals, rejected)
            return signals, rejected

        _dbg_log.smc_ideas(raw_ideas)
        logger.info(f"SignalGenerator: {len(raw_ideas)} raw SMC idea(s)")

        # ── Step 5: Per-idea confluence + validation ──────────────────────────
        for idea_num, idea in enumerate(raw_ideas, 1):

            _dbg_log.idea_start(idea_num, idea)

            # ── 5a: Confluence vote ───────────────────────────────────────────
            smc_verdict    = self._build_smc_verdict(idea)
            confluence     = self._compute_confluence(
                idea.direction, smc_verdict, trend_verdict, liq_verdict
            )

            _dbg_log.confluence(idea.direction, confluence)
            logger.debug(f"  Confluence: {confluence.summary_str()}")

            # Conflict → hard reject
            if confluence.conflict_detected:
                reject_reason = (
                    f"Strategy conflict on {idea.direction}: "
                    f"{confluence.agreeing} agree, "
                    f"{confluence.conflicting} conflict. "
                    f"{confluence.summary_str()}"
                )
                rejected.append(RejectedIdea(
                    idea   = idea,
                    reason = reject_reason,
                    stage  = "strategy_conflict",
                ))
                _dbg_log.gate_reject("strategy_conflict", reject_reason, idea)
                logger.debug(f"  ❌ Rejected (conflict): {idea.direction}")
                continue

            # ── 5b: Full validation gate chain ───────────────────────────────
            result = self.generate_from_idea(
                idea             = idea,
                df_m15           = df_m15,
                account_balance  = account_balance,
                trend_result     = trend_result,
                regime_label     = regime_result.regime,
                sess_ok          = sess_ok,
                vol_ok           = vol_ok,
                news_ok          = news_ok,
                now              = now,
                confluence       = confluence,
            )

            if isinstance(result, TradingSignal):
                signals.append(result)
                self._signals_today.append(result)
                _dbg_log.signal_approved(result)
                logger.info(
                    f"SignalGenerator: APPROVED — {result}  "
                    f"confluence={result.confluence_count}/3"
                )

            elif isinstance(result, RejectedIdea):
                rejected.append(result)
                logger.debug(
                    f"SignalGenerator: REJECTED [{result.stage}] — {result.reason}"
                )

        _dbg_log.cycle_summary(signals, rejected)
        logger.info(
            f"SignalGenerator: cycle done — "
            f"{len(signals)} approved, {len(rejected)} rejected"
        )
        return signals, rejected

    def generate_from_idea(
        self,
        idea:            TradeIdea,
        df_m15:          pd.DataFrame,
        account_balance: float,
        trend_result:    Optional[TrendResult]      = None,
        regime_label:    Optional[RegimeLabel]      = None,
        sess_ok:         bool                       = True,
        vol_ok:          bool                       = True,
        news_ok:         bool                       = True,
        now:             Optional[datetime]         = None,
        confluence:      Optional[ConfluenceResult] = None,
    ) -> TradingSignal | RejectedIdea:
        """
        Validate a single TradeIdea through all gates and return a TradingSignal.

        This is also the entry point used by the backtesting engine.
        `confluence` may be None (e.g., when called from backtester), in which
        case a neutral ConfluenceResult is assumed (zero boost).

        Returns TradingSignal on success, RejectedIdea on any gate failure.
        """
        now = now or datetime.now(timezone.utc)

        # ── Gate 1: News blackout (hard reject) ──────────────────────────────
        if not news_ok:
            _dbg_log.gate_reject("news_filter", "News blackout active", idea)
            return RejectedIdea(
                idea   = idea,
                reason = "News blackout active",
                stage  = "news_filter",
            )

        # ── Gate 2: Trend alignment ───────────────────────────────────────────
        if trend_result is None:
            trend_result = TrendResult()

        trend_aligned = trend_result.allows_direction(idea.direction)
        if not trend_aligned and trend_result.direction not in (
            TrendDirection.NEUTRAL, TrendDirection.UNKNOWN
        ):
            reason = (
                f"Trend misalignment: signal={idea.direction}, "
                f"trend={trend_result.direction.value}"
            )
            _dbg_log.gate_reject("trend_alignment", reason, idea)
            return RejectedIdea(
                idea   = idea,
                reason = reason,
                stage  = "trend_alignment",
            )
        _dbg_log.gate_pass(
            "trend_alignment",
            f"signal={idea.direction} trend={trend_result.direction.value}",
        )

        # ── Gate 3: Regime suitability ────────────────────────────────────────
        if regime_label in (RegimeLabel.RANGING, RegimeLabel.LOW_VOLATILITY):
            if idea.confidence < 0.65:
                reason = (
                    f"Regime={regime_label.value} with low SMC "
                    f"confidence ({idea.confidence:.0%} < 0.65)"
                )
                _dbg_log.gate_reject("regime_gate", reason, idea)
                return RejectedIdea(
                    idea   = idea,
                    reason = reason,
                    stage  = "regime_gate",
                )
        _dbg_log.gate_pass(
            "regime_gate",
            regime_label.value if regime_label else "N/A",
        )

        # ── Step 4: Confidence rescoring ──────────────────────────────────────
        if confluence is None:
            confluence = ConfluenceResult(direction=idea.direction, agreeing=1)

        final_confidence, breakdown = self._rescore_confidence(
            base_score   = idea.confidence,
            idea         = idea,
            trend_result = trend_result,
            regime_label = regime_label,
            df_m15       = df_m15,
            sess_ok      = sess_ok,
            vol_ok       = vol_ok,
            news_ok      = news_ok,
            now          = now,
            confluence   = confluence,
        )

        _dbg_log.confidence_breakdown(
            base      = idea.confidence,
            breakdown = breakdown,
            final     = final_confidence,
            threshold = self.cfg.CONFIDENCE_THRESHOLD,
        )

        # ── Gate 5: Minimum confidence ────────────────────────────────────────
        if final_confidence < self.cfg.CONFIDENCE_THRESHOLD:
            reason = (
                f"Confidence {final_confidence:.0%} < "
                f"threshold {self.cfg.CONFIDENCE_THRESHOLD:.0%}"
            )
            _dbg_log.gate_reject("confidence_threshold", reason, idea)
            return RejectedIdea(
                idea   = idea,
                reason = reason,
                stage  = "confidence_threshold",
            )
        _dbg_log.gate_pass(
            "confidence_threshold",
            f"{final_confidence:.1%} ≥ {self.cfg.CONFIDENCE_THRESHOLD:.1%}",
        )

        # ── Step 6: Position sizing ───────────────────────────────────────────
        try:
            sizing = self.sizer.calculate(
                entry_price     = idea.entry,
                stop_loss       = idea.stop_loss,
                take_profit_1   = idea.take_profit,
                take_profit_2   = idea.take_profit_2,
                account_balance = account_balance,
            )
        except Exception as exc:
            _dbg_log.gate_reject("position_sizing", str(exc), idea)
            return RejectedIdea(
                idea   = idea,
                reason = f"Position sizing failed: {exc}",
                stage  = "position_sizing",
            )

        # ── Gate 7: R:R threshold ─────────────────────────────────────────────
        rr = sizing.rr_ratio_tp1 or 0.0
        if rr < self.cfg.MIN_RR_RATIO:
            reason = f"R:R {rr:.2f} < minimum {self.cfg.MIN_RR_RATIO:.1f}:1"
            _dbg_log.gate_reject("rr_ratio", reason, idea)
            return RejectedIdea(
                idea   = idea,
                reason = reason,
                stage  = "rr_ratio",
            )
        _dbg_log.gate_pass("rr_ratio", f"R:R {rr:.2f} ≥ {self.cfg.MIN_RR_RATIO:.1f}")

        # ── Step 8: Assemble TradingSignal ────────────────────────────────────
        session = self.session_f.current_session(now)
        signal  = TradingSignal(
            symbol              = self.cfg.SYMBOL,
            direction           = idea.direction,
            timestamp           = now,
            entry_price         = idea.entry,
            stop_loss           = idea.stop_loss,
            take_profit_1       = idea.take_profit,
            take_profit_2       = idea.take_profit_2,
            lot_size            = sizing.lot_size,
            risk_amount_usd     = sizing.risk_amount_usd,
            risk_pct            = sizing.actual_risk_pct,
            rr_ratio_tp1        = sizing.rr_ratio_tp1,
            rr_ratio_tp2        = sizing.rr_ratio_tp2,
            monetary_value_1pt  = sizing.monetary_value_1pt,
            confidence          = round(final_confidence, 3),
            smc_confidence      = round(idea.confidence, 3),
            trend_strength      = round(trend_result.strength, 3),
            regime              = regime_label.value if regime_label else "",
            session             = session,
            trend_direction     = trend_result.direction.value,
            has_ob              = idea.has_ob,
            has_fvg             = idea.has_fvg,
            has_bos             = idea.has_bos,
            has_choch           = idea.has_choch,
            has_liquidity_sweep = idea.has_liquidity_sweep,
            confluence_count    = confluence.agreeing,
            confluence_boost    = confluence.confluence_boost,
            strategy_verdicts   = confluence.verdicts,
            confidence_breakdown = breakdown,
            notes               = idea.notes,
        )
        return signal

    # =========================================================================
    # STRATEGY SUB-ENGINES
    # =========================================================================

    def _run_trend_strategy(self, trend_result: TrendResult) -> StrategyVerdict:
        """
        Strategy A: Trend Strategy verdict.

        Logic
        -----
        • BULLISH trend (direction=BULLISH, strength > 0.30) → BUY verdict
        • BEARISH trend (direction=BEARISH, strength > 0.30) → SELL verdict
        • NEUTRAL / UNKNOWN / strength ≤ 0.30               → NEUTRAL (abstain)

        The strength threshold ensures the trend is meaningful — weak or
        oscillating EMAs don't produce a directional opinion.
        """
        MIN_TREND_STRENGTH = 0.30

        if (trend_result.direction == TrendDirection.BULLISH
                and trend_result.strength >= MIN_TREND_STRENGTH):
            return StrategyVerdict(
                strategy_name = "TREND",
                direction     = "BUY",
                confidence    = round(trend_result.strength, 3),
                active        = True,
                reason        = (
                    f"BULLISH EMA structure  "
                    f"str={trend_result.strength:.0%}  "
                    f"EMA50={trend_result.ema_50:.2f}  "
                    f"EMA200={trend_result.ema_200:.2f}"
                ),
            )

        if (trend_result.direction == TrendDirection.BEARISH
                and trend_result.strength >= MIN_TREND_STRENGTH):
            return StrategyVerdict(
                strategy_name = "TREND",
                direction     = "SELL",
                confidence    = round(trend_result.strength, 3),
                active        = True,
                reason        = (
                    f"BEARISH EMA structure  "
                    f"str={trend_result.strength:.0%}  "
                    f"EMA50={trend_result.ema_50:.2f}  "
                    f"EMA200={trend_result.ema_200:.2f}"
                ),
            )

        return StrategyVerdict(
            strategy_name = "TREND",
            direction     = "NEUTRAL",
            confidence    = 0.0,
            active        = False,
            reason        = (
                f"No clear trend  "
                f"dir={trend_result.direction.value}  "
                f"str={trend_result.strength:.0%}"
            ),
        )

    def _run_liq_sweep_strategy(
        self, liq_sweep: Optional[LiquiditySweep]
    ) -> StrategyVerdict:
        """
        Strategy C: Liquidity Sweep Strategy verdict.

        Logic
        -----
        A CONFIRMED liquidity sweep is a directional signal:
          Sweep LOW  → BUY  (sell-side stops grabbed → institutions going long)
          Sweep HIGH → SELL (buy-side stops grabbed  → institutions going short)

        A LOW-quality sweep earns NEUTRAL (not strong enough to corroborate).
        No sweep at all → NEUTRAL (strategy abstains).
        """
        from strategy.liquidity_detection import SweepQuality

        if liq_sweep is None:
            return StrategyVerdict(
                strategy_name = "LIQUIDITY_SWEEP",
                direction     = "NEUTRAL",
                confidence    = 0.0,
                active        = False,
                reason        = "No recent liquidity sweep detected",
            )

        if liq_sweep.quality == SweepQuality.LOW:
            return StrategyVerdict(
                strategy_name = "LIQUIDITY_SWEEP",
                direction     = "NEUTRAL",
                confidence    = 0.0,
                active        = False,
                reason        = (
                    f"Sweep quality too low ({liq_sweep.quality.value}) — "
                    f"not corroborating"
                ),
            )

        return StrategyVerdict(
            strategy_name = "LIQUIDITY_SWEEP",
            direction     = liq_sweep.direction,   # "BUY" or "SELL"
            confidence    = round(liq_sweep.quality_score, 3),
            active        = True,
            reason        = (
                f"Sweep {liq_sweep.type.value}  "
                f"level={liq_sweep.sweep_price:.2f}  "
                f"wick={liq_sweep.wick_atr_ratio:.2f}×ATR  "
                f"quality={liq_sweep.quality.value}({liq_sweep.quality_score:.0%})  "
                f"{'CONFIRMED' if liq_sweep.confirmed else 'unconfirmed'}"
            ),
        )

    def _build_smc_verdict(self, idea: TradeIdea) -> StrategyVerdict:
        """
        Build a StrategyVerdict from a TradeIdea for use in the confluence vote.

        The SMC strategy is always active when a TradeIdea exists.
        """
        # Count SMC components present
        component_count = sum([
            idea.has_ob, idea.has_fvg, idea.has_bos,
            idea.has_choch, idea.has_liquidity_sweep,
        ])
        return StrategyVerdict(
            strategy_name = "SMC",
            direction     = idea.direction,
            confidence    = round(idea.confidence, 3),
            active        = True,
            reason        = (
                f"SMC setup  "
                f"conf={idea.confidence:.0%}  "
                f"components={component_count}  "
                f"{'OB ' if idea.has_ob else ''}"
                f"{'FVG ' if idea.has_fvg else ''}"
                f"{'BOS ' if idea.has_bos else ''}"
                f"{'CHoCH ' if idea.has_choch else ''}"
                f"{'Sweep' if idea.has_liquidity_sweep else ''}"
            ).strip(),
        )

    # =========================================================================
    # CONFLUENCE ENGINE
    # =========================================================================

    def _compute_confluence(
        self,
        candidate_direction: str,
        smc_verdict:         StrategyVerdict,
        trend_verdict:       StrategyVerdict,
        liq_verdict:         StrategyVerdict,
    ) -> ConfluenceResult:
        """
        Count how many active strategies agree / conflict on a candidate direction.

        Parameters
        ----------
        candidate_direction : "BUY" or "SELL" — direction proposed by the SMC idea
        smc_verdict         : SMC strategy verdict (always active here)
        trend_verdict       : Trend strategy verdict
        liq_verdict         : Liquidity sweep strategy verdict

        Returns
        -------
        ConfluenceResult with agreeing count, conflict flag, and boost.
        """
        all_verdicts = [smc_verdict, trend_verdict, liq_verdict]
        active       = [v for v in all_verdicts if v.active]

        agreeing    = 0
        conflicting = 0

        for v in active:
            if v.direction == candidate_direction:
                agreeing += 1
            elif v.direction != "NEUTRAL":
                conflicting += 1

        conflict_detected = conflicting > 0
        boost = _CONFLUENCE_BOOST.get(agreeing, 0.0) if not conflict_detected else 0.0

        logger.debug(
            f"  confluence({candidate_direction}): "
            f"active={len(active)} "
            f"agree={agreeing} "
            f"conflict={conflicting} "
            f"boost={boost:+.0%}"
        )

        return ConfluenceResult(
            direction         = candidate_direction,
            total_active      = len(active),
            agreeing          = agreeing,
            conflicting       = conflicting,
            conflict_detected = conflict_detected,
            confluence_boost  = boost,
            verdicts          = all_verdicts,
        )

    # =========================================================================
    # CONFIDENCE RESCORING
    # =========================================================================

    def _rescore_confidence(
        self,
        base_score:   float,
        idea:         TradeIdea,
        trend_result: TrendResult,
        regime_label: Optional[RegimeLabel],
        df_m15:       pd.DataFrame,
        sess_ok:      bool,
        vol_ok:       bool,
        news_ok:      bool,
        now:          datetime,
        confluence:   ConfluenceResult,
    ) -> tuple[float, dict]:
        """
        Adjust the raw SMC confidence score with all contextual and
        confluence factors.

        Returns (final_score: float, breakdown: dict).

        Breakdown keys:
          smc_base, confluence_boost, trend_alignment, trend_strength,
          regime_delta, session_delta, volatility_delta, news_delta,
          liq_sweep_delta, ob_fvg_overlap
        """
        score = base_score
        bd: dict[str, float] = {"smc_base": round(base_score, 3)}

        # ── Confluence boost ──────────────────────────────────────────────────
        score += confluence.confluence_boost
        bd["confluence_boost"] = confluence.confluence_boost

        # ── Trend alignment bonus ─────────────────────────────────────────────
        trend_dir = trend_result.direction
        if ((idea.direction == "BUY"  and trend_dir == TrendDirection.BULLISH) or
                (idea.direction == "SELL" and trend_dir == TrendDirection.BEARISH)):
            delta = +0.10
        elif trend_dir in (TrendDirection.NEUTRAL, TrendDirection.UNKNOWN):
            delta = 0.0
        else:
            delta = -0.08
        score += delta
        bd["trend_alignment"] = delta

        # ── Trend strength bonus (pro-rata 0–8%) ──────────────────────────────
        if ((trend_dir == TrendDirection.BULLISH and idea.direction == "BUY") or
                (trend_dir == TrendDirection.BEARISH and idea.direction == "SELL")):
            str_delta = trend_result.strength * 0.08
        else:
            str_delta = 0.0
        score += str_delta
        bd["trend_strength"] = round(str_delta, 3)

        # ── Regime delta ──────────────────────────────────────────────────────
        regime_delta = {
            RegimeLabel.TRENDING:        +0.05,
            RegimeLabel.RANGING:         -0.15,
            RegimeLabel.HIGH_VOLATILITY: -0.10,
            RegimeLabel.LOW_VOLATILITY:  -0.10,
        }.get(regime_label, 0.0)
        score += regime_delta
        bd["regime_delta"] = regime_delta

        # ── Session delta ─────────────────────────────────────────────────────
        sess_delta = self.session_f.confidence_delta(now)
        score += sess_delta
        bd["session_delta"] = sess_delta

        # ── Volatility delta ──────────────────────────────────────────────────
        vol_delta = self.volatility_f.confidence_delta(df_m15)
        score += vol_delta
        bd["volatility_delta"] = vol_delta

        # ── News delta (soft — news hard-blocks happen earlier) ───────────────
        news_delta = self.news_f.confidence_delta(now)
        score += news_delta
        bd["news_delta"] = news_delta

        # ── Liquidity sweep alignment bonus ───────────────────────────────────
        # If the liq sweep strategy was active and agrees → extra boost
        # (beyond the vote count — it's contextually very strong confirmation)
        liq_v = next(
            (v for v in confluence.verdicts if v.strategy_name == "LIQUIDITY_SWEEP"),
            None,
        )
        if liq_v and liq_v.active:
            if liq_v.direction == idea.direction:
                liq_delta = +0.05
            else:
                liq_delta = -0.10   # active sweep in opposite direction is notable
        else:
            liq_delta = 0.0
        score += liq_delta
        bd["liq_sweep_delta"] = liq_delta

        # ── OB + FVG overlap bonus ─────────────────────────────────────────────
        if idea.has_ob and idea.has_fvg:
            overlap_delta = +0.05
            score += overlap_delta
            bd["ob_fvg_overlap"] = overlap_delta

        # ── Clamp ─────────────────────────────────────────────────────────────
        final = round(min(max(score, 0.0), 1.0), 4)
        bd["final"] = final

        return final, bd

