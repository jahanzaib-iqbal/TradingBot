    # =========================================================================

    def _reset_daily_counter(self, now: datetime) -> None:
        """Reset the daily signal counter if the date has rolled over."""
        today = now.date()
        last  = self._last_reset_date.date() if self._last_reset_date else None
        if last != today:
            self._signals_today.clear()
            self._last_reset_date = now
            logger.info(f"SignalGenerator: daily counter reset for {today}")

    @property
    def signals_today(self) -> int:
        """Number of signals already dispatched today."""
        return len(self._signals_today)

    @property
    def daily_cap_reached(self) -> bool:
        """True if the daily signal cap has been hit."""
        return self.signals_today >= self.cfg.MAX_SIGNALS_PER_DAY

