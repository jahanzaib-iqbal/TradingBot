    def _get_trend(self, df_h1: pd.DataFrame) -> TrendResult:
        """Run TrendDetector on H1 data; return safe default on error."""
        try:
            return self.trend_detector.detect(df_h1)
        except Exception as exc:
            logger.warning(f"_get_trend() failed: {exc}")
            return TrendResult()

    def _get_regime(self, df_h1: pd.DataFrame):
        """Run MarketRegimeClassifier on H1 data; return safe default on error."""
        try:
            return self.regime_clf.classify(df_h1)
        except Exception as exc:
            logger.warning(f"_get_regime() failed: {exc}")
            from strategy.market_regime import RegimeResult
            return type("_DefaultRegime", (), {"regime": RegimeLabel.TRENDING})()

    def _get_liquidity_sweep(
        self, df_m15: pd.DataFrame
    ) -> Optional[LiquiditySweep]:
        """Run LiquiditySweepDetector; return the latest sweep or None."""
        try:
            return self.liq_detector.get_latest_sweep(df_m15)
        except Exception as exc:
            logger.warning(f"_get_liquidity_sweep() failed: {exc}")
            return None

    def _scan_smc(self, df: pd.DataFrame) -> list[TradeIdea]:
        """Run SmartMoneyStrategy scanner; return empty list on error."""
        try:
            return self.smc.scan(df)
        except Exception as exc:
            logger.error(f"_scan_smc() failed: {exc}")
            return []

