@dataclass
class StrategyVerdict:
    """
    The opinion of one strategy sub-engine on the current market.

    Used by the multi-strategy confluence engine to combine views.

    Attributes
    ----------
    strategy_name : Human-readable name ("TREND" | "SMC" | "LIQUIDITY_SWEEP")
    direction     : "BUY" | "SELL" | "NEUTRAL"
    confidence    : 0.0 – 1.0 — the strategy's own certainty score
    active        : True if the strategy found a valid setup.
                    False = no setup detected (strategy abstains from voting)
    reason        : Plain-English explanation of the verdict
    """
    strategy_name: str
    direction:     str     = "NEUTRAL"
    confidence:    float   = 0.0
    active:        bool    = False
    reason:        str     = ""

    @property
    def is_buy(self)  -> bool: return self.active and self.direction == "BUY"
    @property
    def is_sell(self) -> bool: return self.active and self.direction == "SELL"

    def __str__(self) -> str:
        flag = "✅" if self.active else "⬜"
        return (
            f"{flag} {self.strategy_name:<18} "
            f"dir={self.direction:<7} "
            f"conf={self.confidence:.0%}  "
            f"{self.reason[:55]}"
        )


