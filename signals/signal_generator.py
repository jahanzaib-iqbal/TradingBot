@dataclass
class TradingSignal:
    """
    A fully validated, publication-ready trading signal.

    All fields are populated before the signal is emitted to Telegram.
    The to_dict() method produces the machine-readable version.
    """
    # ── Identity ──────────────────────────────────────────────────────────────
    symbol:    str
    direction: str                        # "BUY" | "SELL"
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    # ── Trade levels ──────────────────────────────────────────────────────────
    entry_price:   float = 0.0
    stop_loss:     float = 0.0
    take_profit_1: float = 0.0
    take_profit_2: Optional[float] = None

    # ── Risk / sizing ─────────────────────────────────────────────────────────
    lot_size:           float = 0.0
    risk_amount_usd:    float = 0.0
    risk_pct:           float = 0.0
    rr_ratio_tp1:       Optional[float] = None
    rr_ratio_tp2:       Optional[float] = None
    monetary_value_1pt: float = 0.0

    # ── Scores ────────────────────────────────────────────────────────────────
    confidence:     float = 0.0           # final composite score [0, 1]
    smc_confidence: float = 0.0           # raw SMC score before adjustments
    trend_strength: float = 0.0           # TrendResult.strength

    # ── Context ───────────────────────────────────────────────────────────────
    regime:          str = ""             # RegimeLabel.value
    session:         str = ""             # "london" | "new_york" | ...
    trend_direction: str = ""             # "BULLISH" | "BEARISH" | "NEUTRAL"

    # ── SMC evidence flags ────────────────────────────────────────────────────
    has_ob:              bool = False
    has_fvg:             bool = False
    has_bos:             bool = False
    has_choch:           bool = False
    has_liquidity_sweep: bool = False

    # ── Multi-strategy confluence (new) ───────────────────────────────────────
    confluence_count:   int   = 0         # how many strategies agreed
    confluence_boost:   float = 0.0       # boost applied to confidence
    strategy_verdicts:  list  = field(default_factory=list)   # list[StrategyVerdict]

    # ── Confidence breakdown (for transparency / logs) ────────────────────────
    confidence_breakdown: dict = field(default_factory=dict)

    # ── Raw idea reference (for debugging) ────────────────────────────────────
    notes: str = ""

    # =========================================================================
    # OUTPUT HELPERS
    # =========================================================================

    def to_dict(self) -> dict:
        """Return a machine-readable dict for signal logging and Telegram formatting."""
        def r(v, d=2):
            return round(v, d) if v is not None else None

        return {
            "symbol":            self.symbol,
            "direction":         self.direction,
            "timestamp":         self.timestamp.isoformat(),
            "entry_price":       r(self.entry_price),
            "stop_loss":         r(self.stop_loss),
            "take_profit_1":     r(self.take_profit_1),
            "take_profit_2":     r(self.take_profit_2),
            "lot_size":          r(self.lot_size),
            "risk_amount_usd":   r(self.risk_amount_usd),
            "risk_pct":          r(self.risk_pct),
            "rr_ratio_tp1":      r(self.rr_ratio_tp1),
            "rr_ratio_tp2":      r(self.rr_ratio_tp2),
            "confidence":        r(self.confidence, 3),
            "smc_confidence":    r(self.smc_confidence, 3),
            "trend_strength":    r(self.trend_strength, 3),
            "regime":            self.regime,
            "session":           self.session,
            "trend_direction":   self.trend_direction,
            "has_ob":            self.has_ob,
            "has_fvg":           self.has_fvg,
            "has_bos":           self.has_bos,
            "has_choch":         self.has_choch,
            "has_liquidity_sweep": self.has_liquidity_sweep,
            "confluence_count":  self.confluence_count,
            "confluence_boost":  r(self.confluence_boost, 3),
            "notes":             self.notes,
        }



    def __str__(self) -> str:
        return (
            f"TradingSignal({self.direction} {self.symbol} | "
            f"E={self.entry_price:.2f} SL={self.stop_loss:.2f} "
            f"TP={self.take_profit_1:.2f} | "
            f"lot={self.lot_size:.2f} risk=${self.risk_amount_usd:.0f} | "
            f"conf={self.confidence:.0%} confluence={self.confluence_count} | "
            f"sess={self.session} regime={self.regime})"
        )


